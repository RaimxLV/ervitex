), gone AS (
  SELECT c.source, c.sku, c.style_code, c.retail_price FROM public.catalog_variant_prices c
   WHERE (c.source = 'mf' AND c.style_code IN (SELECT style_code FROM public.mf_styles WHERE upper(COALESCE(raw->>'categoryName','')) = 'OUTLET'))
      OR (c.source = 'utt' AND lower(c.sku) IN (SELECT lower(sku) FROM utt_o))
      OR (c.source = 'ss' AND c.sku IN (SELECT v.sku FROM public.ss_variants v
            LEFT JOIN public.ss_prices p ON p.sku = v.sku AND p.purchase_price > 0
           WHERE v.published AND p.sku IS NULL))
), styles AS (
  SELECT g.source, g.style_code,
         r.min_price AS before_min, r.max_price AS before_max,
         (SELECT min(c.retail_price) FROM public.catalog_variant_prices c
           WHERE c.source = g.source AND c.style_code = g.style_code
             AND c.sku NOT IN (SELECT sku FROM gone WHERE source = g.source)) AS after_min,
         (SELECT max(c.retail_price) FROM public.catalog_variant_prices c
           WHERE c.source = g.source AND c.style_code = g.style_code
             AND c.sku NOT IN (SELECT sku FROM gone WHERE source = g.source)) AS after_max
    FROM (SELECT DISTINCT source, style_code FROM gone) g
    LEFT JOIN public.catalog_price_ranges r ON r.source = g.source AND r.style_code = g.style_code
)
SELECT source,
       (SELECT count(*) FROM gone x WHERE x.source = s.source) AS price_rows_removed,
       count(*) AS styles_touched,
       count(*) FILTER (WHERE after_min IS NULL) AS styles_leaving_catalog,
       count(*) FILTER (WHERE after_min IS NOT NULL AND after_min <> before_min) AS from_price_changed,
       round(max(after_min - before_min), 2) AS max_from_price_rise
  FROM styles s GROUP BY source ORDER BY source;
